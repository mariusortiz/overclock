"""Measures the Blaster Kit gun models and writes scripts/weapon_models.gd.

Run from the repo root: python3 tools/make_weapon_table.py
The kit's guns point toward -Z. For each one we record its bounding box, the
height of the barrel at the muzzle and the height of its top in the middle,
so the game can place it in a hand and mount accessories without hand tuning.
"""
import glob
import json
import os
import struct

MODEL_DIR = "assets/models/blasters/"


def read_vertices(path):
    with open(path, "rb") as f:
        f.read(12)
        json_length, _ = struct.unpack("<I4s", f.read(8))
        gltf = json.loads(f.read(json_length))
        binary_length, _ = struct.unpack("<I4s", f.read(8))
        binary = f.read(binary_length)
    # Node translations matter for parts such as magazines.
    offsets = {}
    for node in gltf["nodes"]:
        if "mesh" in node:
            offsets[node["mesh"]] = node.get("translation", [0, 0, 0])
    vertices = []
    for mesh_index, mesh in enumerate(gltf["meshes"]):
        ox, oy, oz = offsets.get(mesh_index, [0, 0, 0])
        for primitive in mesh["primitives"]:
            accessor = gltf["accessors"][primitive["attributes"]["POSITION"]]
            view = gltf["bufferViews"][accessor["bufferView"]]
            start = view.get("byteOffset", 0) + accessor.get("byteOffset", 0)
            stride = view.get("byteStride", 12)
            for i in range(accessor["count"]):
                x, y, z = struct.unpack_from("<fff", binary, start + i * stride)
                vertices.append((x + ox, y + oy, z + oz))
    return vertices


lines = ["class_name WeaponModels",
         "## Generated by tools/make_weapon_table.py: do not edit by hand.",
         "## Measurements of the Blaster Kit guns, which point toward -Z.",
         '## "barrel_y" is the height of the barrel at the muzzle, "top_y" the height',
         "## of the gun's top around its middle (where a scope sits).", "",
         "const DATA := {"]
for path in sorted(glob.glob(MODEL_DIR + "blaster-*.glb")):
    vertices = read_vertices(path)
    lo = [min(v[i] for v in vertices) for i in range(3)]
    hi = [max(v[i] for v in vertices) for i in range(3)]
    length = hi[2] - lo[2]
    front = [v for v in vertices if v[2] <= lo[2] + 0.06 * length]
    barrel_y = (min(v[1] for v in front) + max(v[1] for v in front)) / 2
    middle = [v for v in vertices if lo[2] + 0.35 * length <= v[2] <= lo[2] + 0.65 * length]
    top_y = max(v[1] for v in middle)
    name = os.path.basename(path)[:-4]
    lines.append('\t"%s": {"min": Vector3(%.3f, %.3f, %.3f), "max": Vector3(%.3f, %.3f, %.3f), "barrel_y": %.3f, "top_y": %.3f},'
                 % (name, *lo, *hi, barrel_y, top_y))
lines += ["}", ""]
open("scripts/weapon_models.gd", "w").write("\n".join(lines))
