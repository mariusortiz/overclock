"""Measures the gun models and writes scripts/weapon_models.gd.

Run from the repo root: python3 tools/make_weapon_table.py
The guns (Quaternius, .obj) lie along +X, muzzle at the high end, grip near
the origin. For each one we record its bounding box, the height of the barrel
at the muzzle and the height of its top around the middle, so the game can
place it in a hand and mount accessories without hand tuning.
"""
import glob
import os

MODEL_DIR = "assets/models/guns/"
ACCESSORIES = ("Scope", "Silencer")


def read_vertices(path):
    vertices = []
    for line in open(path, errors="replace"):
        if line.startswith("v "):
            vertices.append(tuple(float(value) for value in line.split()[1:4]))
    return vertices


lines = ["class_name WeaponModels",
         "## Generated by tools/make_weapon_table.py: do not edit by hand.",
         "## Measurements of the gun models, which lie along +X (muzzle at max x).",
         '## "barrel_y" is the height of the barrel at the muzzle, "top_y" the height',
         "## of the gun's top around its middle (where a scope sits).", "",
         "const DATA := {"]
for path in sorted(glob.glob(MODEL_DIR + "*.obj")):
    name = os.path.basename(path)[:-4]
    if name.startswith(ACCESSORIES):
        continue
    vertices = read_vertices(path)
    lo = [min(v[i] for v in vertices) for i in range(3)]
    hi = [max(v[i] for v in vertices) for i in range(3)]
    length = hi[0] - lo[0]
    front = [v for v in vertices if v[0] >= hi[0] - 0.06 * length]
    barrel_y = (min(v[1] for v in front) + max(v[1] for v in front)) / 2
    middle = [v for v in vertices if lo[0] + 0.35 * length <= v[0] <= lo[0] + 0.65 * length]
    top_y = max(v[1] for v in middle)
    lines.append('\t"%s": {"min": Vector3(%.3f, %.3f, %.3f), "max": Vector3(%.3f, %.3f, %.3f), "barrel_y": %.3f, "top_y": %.3f},'
                 % (name, *lo, *hi, barrel_y, top_y))
lines += ["}", ""]
open("scripts/weapon_models.gd", "w").write("\n".join(lines))
